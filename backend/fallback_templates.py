def get_fallback_message(category: str) -> str:
    """주어진 카테고리에 맞는 안전한 역질문(Fallback) 메시지를 반환합니다."""
    # 카테고리가 사전에 없으면 UNKNOWN을 반환
    return FALLBACK_TEMPLATES.get(category, FALLBACK_TEMPLATES["UNKNOWN"])
