def get_synonyms(text: str) -> list:
    """[v5.3.0] 경량화된 동의어 엔진 - 최소한의 앵커 매핑만 수행"""
    if not text:
        return []
    
    synonyms = set()
    input_words = text.replace('?', ' ').replace('.', ' ').split()
    
    for key, values in LEGAL_SYNONYMS.items():
        # 완전 일치: 텍스트 내에 키가 포함된 경우
        if key in text:
            synonyms.update(values)
            continue
            
        # 복합어(공백 포함): 모든 부분 단어가 텍스트에 있어야 매칭
        if " " in key:
            parts = key.split()
            if all(p in text for p in parts):
                synonyms.update(values)
            continue
        
        # [v5.3.0 Restored] 단일 단어 접두/접미 부분 매칭 (조사/어미 변형 대응)
        # '뺑소니를', '칼치기야' 같은 조사 변형을 탐지
        if len(key) >= 2:
            for word in input_words:
                if (key[:2] in word or key[-2:] in word) and len(word) >= 2:
                    synonyms.update(values)
                    break
    
    return list(synonyms)

from typing import Optional
def guess_category(keywords: list) -> Optional[str]:
    """[v5.3.0] 키워드 기반 카테고리 추론"""
    category_scores = {k: 0 for k in CATEGORY_KEYWORDS.keys()}
    full_text = " ".join(keywords)
    
    # 복합 키워드 가중치
    if any(k in full_text for k in ["보험", "보험금"]) and any(k in full_text for k in ["사고", "교통", "치이", "들이받"]):
        category_scores["FRAUD"] += 2

    for kw in keywords:
        for cat, words in CATEGORY_KEYWORDS.items():
            if any(word in kw for word in words):
                category_scores[cat] += 1
                    
    sorted_scores = sorted(category_scores.items(), key=lambda x: x[1], reverse=True)
    top_cat, top_score = sorted_scores[0]
    second_cat, second_score = sorted_scores[1] if len(sorted_scores) > 1 else (None, 0)

    if top_score > 0 and (top_score >= second_score * 1.5 or top_score >= 3.0):
        return top_cat
    
    return None

