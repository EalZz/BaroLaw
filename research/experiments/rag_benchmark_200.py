async def run_benchmark():
    report = []
    report.append("# 📊 RAG 대규모 200건 벤치마킹 데이터 (Full Test)")
    report.append(f"수행 시작 시간: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    report.append("\n## 1. 개요")
    report.append("- 4대 카테고리(형사, 부동산, 사기, 교통) 전수 조사")
    report.append("- Z-Score 통계 보정 및 단어 매칭 가중치(+0.5) 영향도 분석")
    report.append("\n---")

    stats = {"total": len(TEST_QUERIES), "keywords_found": 0, "avg_top1_score": 0.0}

    for i, user_query in enumerate(TEST_QUERIES):
        print(f"[{i+1}/200] {user_query[:30]}...")
        
        # 1. 키워드 추출
        legal_keywords = extract_legal_keywords(user_query)
        if legal_keywords:
            stats["keywords_found"] += 1
        enriched_query = f"{user_query} {legal_keywords}" if legal_keywords else user_query
        
        # 2. RAG 검색 (내부적으로 Z-Score 및 가중치 적용됨)
        # 중요: search_relevant_context는 이미 rag.py에 정의된 최신 로직을 따름
        context = search_relevant_context(enriched_query)
        
        report.append(f"\n### CASE {i+1}. {user_query}")
        report.append(f"> **Gemma 추출 키워드**: `{legal_keywords if legal_keywords else '실패'}`")
        
        results = []
        if context["statutes"]:
            for s in context["statutes"]:
                results.append({"type": "법령", "title": f"{s['law_name']} {s['article']}", "score": s["similarity"]})
        if context["qa"]:
            for q in context["qa"]:
                results.append({"type": "QA", "title": f"Q: {q['question'][:30]}...", "score": q["similarity"]})
        
        if not results:
            report.append("- ❌ **결과 없음 (Filter Out)**")
            continue
            
        stats["avg_top1_score"] += results[0]["score"]

        report.append("| 순위 | 타입 | 제목 | 최종 점수 |")
        report.append("| :--- | :--- | :--- | :--- |")
        for idx, res in enumerate(results):
            report.append(f"| {idx+1} | {res['type']} | {res['title']} | **{res['score']:.4f}** |")

    # 통계 요약
    avg_score = stats["avg_top1_score"] / stats["total"]
    report.insert(7, f"\n## 2. 요약 통계\n- 총 테스트 케이스: {stats['total']}건\n- 키워드 추출 성공률: {(stats['keywords_found']/stats['total'])*100:.1f}%\n- Top 1 평균 점수: {avg_score:.4f}")

    # 파일 저장
    output_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "rag_test_results_200.md")
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(report))
        
    print(f"\n✅ 200건 벤치마킹 완료! 결과 리포트: {output_path}")

if __name__ == "__main__":
    asyncio.run(run_benchmark())
